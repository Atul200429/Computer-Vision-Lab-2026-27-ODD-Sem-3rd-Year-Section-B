image_files = sorted([
    f for f in os.listdir(image_folder)
    if f.lower().endswith((".jpg", ".jpeg", ".png"))
])

image_path = os.path.join(image_folder, image_files[0])
label_path = os.path.join(
    label_folder, os.path.splitext(image_files[0])[0] + ".txt"
)

# Run object detection
result = model.predict(
    source=image_path,
    conf=0.25,
    imgsz=640,
    verbose=False
)[0]

# Read ground-truth labels
ground_truth = []

if os.path.exists(label_path):
    with open(label_path, "r") as file:
        for line in file:
            values = list(map(float, line.split()))
            class_id = int(values[0])
            x_center, y_center, width, height = values[1:5]
            ground_truth.append(
                [class_id, x_center, y_center, width, height]
            )

# Get image dimensions
image = cv2.imread(image_path)
height, width = image.shape[:2]

# Convert predicted boxes to normalized YOLO format
predictions = []

for box in result.boxes:
    class_id = int(box.cls[0])
    x1, y1, x2, y2 = box.xyxy[0].tolist()

    x_center = ((x1 + x2) / 2) / width
    y_center = ((y1 + y2) / 2) / height
    box_width = (x2 - x1) / width
    box_height = (y2 - y1) / height

    predictions.append(
        [class_id, x_center, y_center, box_width, box_height]
    )

# Calculate Intersection over Union (IoU)
def calculate_iou(box1, box2):
    # Boxes are in normalized center-x, center-y, width, height format
    x11 = box1[1] - box1[3] / 2
    y11 = box1[2] - box1[4] / 2
    x12 = box1[1] + box1[3] / 2
    y12 = box1[2] + box1[4] / 2

    x21 = box2[1] - box2[3] / 2
    y21 = box2[2] - box2[4] / 2
    x22 = box2[1] + box2[3] / 2
    y22 = box2[2] + box2[4] / 2

    intersection_width = max(0, min(x12, x22) - max(x11, x21))
    intersection_height = max(0, min(y12, y22) - max(y11, y21))
    intersection = intersection_width * intersection_height

    area1 = box1[3] * box1[4]
    area2 = box2[3] * box2[4]
    union = area1 + area2 - intersection

    return intersection / union if union > 0 else 0

# Match predictions with ground-truth objects
matched_gt = set()
true_positives = 0
false_positives = 0

for pred in predictions:
    best_iou = 0
    best_index = -1

    for i, gt in enumerate(ground_truth):
        if i in matched_gt:
            continue

        if pred[0] == gt[0]:
            iou = calculate_iou(pred, gt)

            if iou > best_iou:
                best_iou = iou
                best_index = i

    if best_index != -1 and best_iou >= 0.50:
        true_positives += 1
        matched_gt.add(best_index)
    else:
        false_positives += 1

false_negatives = len(ground_truth) - len(matched_gt)


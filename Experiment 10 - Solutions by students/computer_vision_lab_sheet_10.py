# Import Required Libraries and Load Dataset
import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow.keras.datasets import mnist

# Load the MNIST dataset
(X_train, y_train), (X_test, y_test) = mnist.load_data()

# Display dataset information
print("Dataset loaded successfully!")
print("Training images shape:", X_train.shape)
print("Training labels shape:", y_train.shape)
print("Testing images shape:", X_test.shape)
print("Testing labels shape:", y_test.shape)
print("Number of classes:", len(np.unique(y_train)))
print("Classes:", np.unique(y_train))

"""**3. Perform image preprocessing by resizing (if required), normalization, and splitting the dataset into training, validation, and testing sets.**"""

from sklearn.model_selection import train_test_split

# Check image dimensions
print("Original image shape:", X_train.shape[1:])

# Resize images if required
# MNIST images are already 28x28, so resizing is not required.

# Normalize pixel values from 0-255 to 0-1
X_train = X_train.astype("float32") / 255.0
X_test = X_test.astype("float32") / 255.0

# Split training data into training and validation sets
X_train, X_val, y_train, y_val = train_test_split(
    X_train,
    y_train,
    test_size=0.2,
    random_state=42,
    stratify=y_train
)

# Display dataset sizes
print("\nDataset split completed successfully!")
print("Training images:", X_train.shape)
print("Training labels:", y_train.shape)
print("Validation images:", X_val.shape)
print("Validation labels:", y_val.shape)
print("Testing images:", X_test.shape)
print("Testing labels:", y_test.shape)

print("\nPixel value range after normalization:",
      X_train.min(), "to", X_train.max())

"""**4. Design a Convolutional Neural Network (CNN) consisting of convolutional layers, pooling layers, activation functions, fully connected layers, and an output layer.**"""

# Design the Convolutional Neural Network (CNN)
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Conv2D, MaxPooling2D, Flatten, Dense, Dropout

# Add channel dimension to the images
X_train = X_train[..., np.newaxis]
X_val = X_val[..., np.newaxis]
X_test = X_test[..., np.newaxis]

# Build the CNN model
model = Sequential([
    Conv2D(32, (3, 3), activation='relu', input_shape=(28, 28, 1)),
    MaxPooling2D(pool_size=(2, 2)),

    Conv2D(64, (3, 3), activation='relu'),
    MaxPooling2D(pool_size=(2, 2)),

    Flatten(),
    Dense(128, activation='relu'),
    Dropout(0.3),

    Dense(10, activation='softmax')
])

# Display the model architecture
model.summary()

"""**5. Configure the model using an appropriate optimizer, loss function, learning rate, batch size, and number of training epochs.**"""

# Configure the CNN Model
from tensorflow.keras.optimizers import Adam

# Configure the model
model.compile(
    optimizer=Adam(learning_rate=0.001),
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# Set training parameters
batch_size = 64
epochs = 10

print("Model compiled successfully!")
print("Optimizer: Adam")
print("Learning rate: 0.001")
print("Loss function: Sparse Categorical Crossentropy")
print("Batch size:", batch_size)
print("Training epochs:", epochs)

"""**6. Train the CNN model using the training dataset and monitor the learning process through training and validation accuracy/loss curves.**"""

# Train the CNN Model
import matplotlib.pyplot as plt

# Train the model
history = model.fit(
    X_train,
    y_train,
    batch_size=batch_size,
    epochs=epochs,
    validation_data=(X_val, y_val),
    verbose=1
)

# Plot training and validation accuracy
plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title('Training and Validation Accuracy')
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend()
plt.grid(True)

# Plot training and validation loss
plt.subplot(1, 2, 2)
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title('Training and Validation Loss')
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend()
plt.grid(True)

plt.tight_layout()
plt.show()

"""**7. Evaluate the trained model on the testing dataset using performance metrics such as Accuracy, Precision, Recall, F1-Score, and Confusion Matrix.**"""


"""**5. Implement the Farneback Dense Optical Flow algorithm to estimate motion for every pixel in the image.**"""

flow = cv2.calcOpticalFlowFarneback(
    gray1,
    gray2,
    None,
    pyr_scale=0.5,
    levels=3,
    winsize=15,
    iterations=3,
    poly_n=5,
    poly_sigma=1.2,
    flags=0
)

print("Farneback Dense Optical Flow calculated.")
print("Flow shape:", flow.shape)

"""**6. Display the dense optical flow output using color-coded motion visualization to represent direction and magnitude.**"""

# Convert flow into magnitude and angle
magnitude, angle = cv2.cartToPolar(
    flow[..., 0],
    flow[..., 1]
)

# Create HSV image
hsv = np.zeros_like(frame2)

hsv[..., 0] = angle * 180 / np.pi / 2
hsv[..., 1] = 255
hsv[..., 2] = cv2.normalize(
    magnitude,
    None,
    0,
    255,
    cv2.NORM_MINMAX
)

# Convert HSV to BGR
dense_output = cv2.cvtColor(
    hsv,
    cv2.COLOR_HSV2BGR
)


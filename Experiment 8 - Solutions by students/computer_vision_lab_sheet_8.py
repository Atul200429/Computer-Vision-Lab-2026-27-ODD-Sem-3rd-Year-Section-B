# Calculate Direction and Magnitude of Motion
import cv2
import numpy as np
import matplotlib.pyplot as plt
import math

cap = cv2.VideoCapture("webcam_video.webm")

ret, old_frame = cap.read()
old_gray = cv2.cvtColor(old_frame, cv2.COLOR_BGR2GRAY)

p0 = cv2.goodFeaturesToTrack(
    old_gray,
    maxCorners=100,
    qualityLevel=0.3,
    minDistance=7
)

lk_params = dict(
    winSize=(15, 15),
    maxLevel=2,
    criteria=(cv2.TERM_CRITERIA_EPS |
              cv2.TERM_CRITERIA_COUNT, 10, 0.03)
)

last_frame = None

while True:
    ret, frame = cap.read()

    if not ret:
        break

    frame_gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

    p1, st, err = cv2.calcOpticalFlowPyrLK(
        old_gray,
        frame_gray,
        p0,
        None,
        **lk_params
    )

    if p1 is None:
        break

    good_new = p1[st == 1]
    good_old = p0[st == 1]

    if len(good_new) == 0:
        break

    for new, old in zip(good_new, good_old):

        x1, y1 = new.ravel()
        x2, y2 = old.ravel()

        dx = x1 - x2
        dy = y1 - y2

        magnitude = math.sqrt(dx**2 + dy**2)
        direction = math.degrees(math.atan2(dy, dx))

        cv2.arrowedLine(
            frame,
            (int(x2), int(y2)),
            (int(x1), int(y1)),
            (255, 0, 0),
            2,
            tipLength=0.3
        )

        cv2.circle(
            frame,
            (int(x1), int(y1)),
            4,
            (0, 0, 255),
            -1
        )

        cv2.putText(
            frame,
            f"Mag: {magnitude:.2f}px Dir: {direction:.1f}°",
            (10, 30),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (0, 255, 0),
            2
        )

    old_gray = frame_gray.copy()
    p0 = good_new.reshape(-1, 1, 2)

    last_frame = frame.copy()

cap.release()

plt.figure(figsize=(10, 6))

"""**3. Apply the Lucas-Kanade Optical Flow algorithm to track the movement of the selected object across consecutive video frames.**"""

# Lucas-Kanade Optical Flow
import cv2
import numpy as np
import matplotlib.pyplot as plt

cap = cv2.VideoCapture("webcam_video.webm")

ret, old_frame = cap.read()
old_gray = cv2.cvtColor(old_frame, cv2.COLOR_BGR2GRAY)

p0 = cv2.goodFeaturesToTrack(
    old_gray,
    maxCorners=100,
    qualityLevel=0.3,
    minDistance=7
)

lk_params = dict(
    winSize=(15, 15),
    maxLevel=2,
    criteria=(cv2.TERM_CRITERIA_EPS |
              cv2.TERM_CRITERIA_COUNT, 10, 0.03)
)

mask = np.zeros_like(old_frame)

while True:
    ret, frame = cap.read()

    if not ret:
        break

    frame_gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

    p1, st, err = cv2.calcOpticalFlowPyrLK(
        old_gray,
        frame_gray,
        p0,
        None,
        **lk_params
    )

    if p1 is None:
        break

    good_new = p1[st == 1]
    good_old = p0[st == 1]

    for new, old in zip(good_new, good_old):
        x1, y1 = new.ravel()
        x2, y2 = old.ravel()

        cv2.line(
            mask,
            (int(x2), int(y2)),
            (int(x1), int(y1)),
            (0, 255, 0),
            2
        )

        cv2.circle(
            frame,
            (int(x1), int(y1)),
            4,
            (0, 0, 255),
            -1
        )

    result = cv2.add(frame, mask)

    old_gray = frame_gray.copy()
    p0 = good_new.reshape(-1, 1, 2)

last_frame = cv2.cvtColor(result, cv2.COLOR_BGR2RGB)

cap.release()

plt.figure(figsize=(10, 6))
plt.imshow(last_frame)
plt.title("Lucas-Kanade Optical Flow Tracking")
plt.axis("off")
plt.show()

